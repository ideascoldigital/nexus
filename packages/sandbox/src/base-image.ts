// Spec 24, piece 3 — the prebuilt base image that makes a dry run affordable.
//
// A local sandbox is byte-identical to a cloud one: `local.ts` calls the same
// `renderCloudInit`, only in container mode. That is the right default and the
// reason the local provider is trustworthy — but it means every run pays apt
// update, build-essential, the NodeSource curl|bash, get.docker.com, a global
// `npm i -g` for the agent CLIs, the gh keyring, a glab .deb and, longest of
// all, `playwright install --with-deps chromium`. Into a bare ubuntu:22.04 with
// no layer cache. That is what the 20-minute ceiling in sandbox-manager is
// calibrated for, and it is most of a dry run's wall clock.
//
// So: bake the tooling once, into an image Docker caches, and let a validation
// run start at the part being validated — stack up, install, build, boot probe.
//
// The image is built from the *same bootstrap sections* the runtime emits, not
// from a second hand-written Dockerfile. A parallel definition is a definition
// that drifts, and the failure it produces is the worst kind: a dry run that
// passes against tooling the real sandbox does not have.

import { AGENT_USER } from "./template";

/**
 * Bumped whenever the baked layers change.
 *
 * Part of the tag, so an older image is never silently reused: a base built
 * before a tooling change would make a dry run answer for a machine that no
 * longer exists. Rebuilding is cheap and wrong answers are not.
 */
export const BASE_IMAGE_VERSION = 2;

/** Ubuntu release the sandboxes are built on — matches the cloud disk image. */
export const BASE_IMAGE_FROM = "ubuntu:22.04";

/** Tag of the prebuilt image, or the fallback when nothing is built yet. */
export const BASE_IMAGE_TAG = `nexux/sandbox-base:v${BASE_IMAGE_VERSION}`;

/**
 * What a dry-run bootstrap can skip because the base already has it.
 *
 * Returned as spec overrides rather than applied inside `renderCloudInit`:
 * the bootstrap should stay a pure function of its spec, and a caller reading
 * this list can see exactly what the speed comes from.
 */
export const DRY_RUN_SKIPS = {
  // The agent CLIs are the point of a real sandbox and irrelevant to whether
  // the project builds. Chromium alone is the single longest install.
  installClaudeCode: false,
  installOpenCode: false,
  installAgentBrowser: false,
  installBrowserSession: false,
  // A tunnel publishes a port for a human to look at. A dry run has no human.
  installCloudflared: false,
  // The tailnet exists so a sandbox can reach private git hosts. A dry run
  // works off bind-mounted checkouts, so there is nothing to reach.
  installTailscale: false,
} as const;

/**
 * The Dockerfile for the base image.
 *
 * Kept deliberately close to the bootstrap's own ordering — apt base, Node,
 * corepack, docker — so a reader comparing the two can see they agree. What it
 * must NOT bake: anything project-specific (env, repos, stack compose) and
 * anything carrying a secret. The image is a tooling cache, not a snapshot of
 * a project.
 *
 * Docker is installed but **not started**: the daemon is launched by the
 * bootstrap's container-mode branch, which already knows to wait for the
 * socket. Baking a running daemon into an image is not possible anyway, and
 * pretending otherwise would hide that wait from the one place that handles it.
 */
export function renderBaseDockerfile(): string {
  return `# Generated by @nexux/sandbox — packages/sandbox/src/base-image.ts
# Spec 24 piece 3: the tooling half of the bootstrap, baked once.
#
# Do not edit by hand. Bump BASE_IMAGE_VERSION and rebuild.
FROM ${BASE_IMAGE_FROM}

ENV DEBIAN_FRONTEND=noninteractive
ENV HOME=/root

# Mirrors the bootstrap's apt base. build-essential brings make/gcc/g++, which
# repo Makefiles and node-gyp native deps both die without.
RUN apt-get update -y \\
 && apt-get install -y --no-install-recommends \\
      git curl ca-certificates gnupg build-essential python3 sudo \\
 && rm -rf /var/lib/apt/lists/*

# The agent user, created here so the checkouts a bind mount brings in are
# already owned correctly. Same uid the bootstrap would create.
RUN id -u ${AGENT_USER} >/dev/null 2>&1 || useradd -m -s /bin/bash ${AGENT_USER} \\
 && echo '${AGENT_USER} ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/${AGENT_USER} \\
 && chmod 440 /etc/sudoers.d/${AGENT_USER} \\
 && mkdir -p /opt/nexus \\
 && chown -R ${AGENT_USER}:${AGENT_USER} /opt/nexus

# Node 22 + corepack shims, exactly as the bootstrap installs them. pnpm and
# yarn are activated here because otherwise they exist only inside the step
# that ran \`corepack enable\`, and a fresh shell dies on "pnpm: not found".
#
# The trailing --version calls are not a smoke test. \`corepack prepare
# --activate\` writes a *shim*; the real binary is downloaded on first use
# ("Downloading the pnpm X binary for linux-arm64"). Invoking each one here
# pulls it into the image — otherwise every dry run pays a network round trip
# for the package manager before it installs anything.
RUN curl -fsSL https://deb.nodesource.com/setup_22.x | bash - \\
 && apt-get install -y --no-install-recommends nodejs \\
 && rm -rf /var/lib/apt/lists/* \\
 && corepack enable \\
 && corepack prepare pnpm@latest --activate \\
 && corepack prepare yarn@stable --activate \\
 && pnpm --version \\
 && yarn --version

# Docker CLI + daemon for the stack services (docker-in-docker). Installed,
# not started: the bootstrap's container branch launches dockerd and waits for
# the socket, and that wait belongs in one place.
RUN curl -fsSL https://get.docker.com | sh \\
 && usermod -aG docker ${AGENT_USER}

# Git ownership: root and the agent share the checkouts.
RUN git config --system --add safe.directory '*'

LABEL org.nexux.base-version="${BASE_IMAGE_VERSION}"
`;
}

/**
 * Whether an image's baked version matches what this build of Nexux expects.
 *
 * Read off the label rather than trusted from the tag: a tag can be retagged,
 * and an image that says it is v1 while holding v0's tooling is exactly the
 * silent wrong answer this whole spec exists to remove.
 */
export function baseImageIsCurrent(label: string | null | undefined): boolean {
  return (label ?? "").trim() === String(BASE_IMAGE_VERSION);
}

/**
 * A spec stripped down to what a validation run actually exercises.
 *
 * Everything removed here is either tooling a dry run does not use (the agent
 * CLIs, Chromium) or reachability it does not need (a tunnel for a human to
 * click, a tailnet for private git hosts it is not cloning from). What stays
 * is the part being validated: the stack services, each repo's install and
 * build, and the boot probe.
 *
 * `installDocker` is deliberately left alone. The caller may have forced it on
 * because the canvas has compose services (`needsDocker`), and a dry run that
 * quietly dropped Docker would report a stack as broken for a reason the real
 * provision would not have.
 */
export function dryRunSpec<T extends Record<string, unknown>>(spec: T): T {
  return { ...spec, ...DRY_RUN_SKIPS };
}
